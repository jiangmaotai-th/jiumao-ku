def main() -> None:
    key_order = list(MARKDOWN["en"].keys())
    for locale, data in MARKDOWN.items():
        missing = [k for k in key_order if k not in data]
        extra = [k for k in data if k not in key_order]
        if missing or extra:
            raise SystemExit(f"{locale} markdown keys mismatch: missing={missing} extra={extra}")

    for path in sorted(LOCALE_DIR.glob("*.ts")):
        if path.name in {"index.ts", "fallbacks.ts"}:
            continue
        locale = path.stem
        if locale not in MARKDOWN:
            raise SystemExit(f"no markdown for {locale}")
        text = path.read_text(encoding="utf-8")
        block = block_from_dict("markdown", {k: MARKDOWN[locale][k] for k in key_order})
        text = replace_or_insert_after(text, "markdown", block, after="legal")
        path.write_text(text, encoding="utf-8")
        print(f"patched markdown → {path.name}")


if __name__ == "__main__":
    main()
