def ts_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def block_from_dict(name: str, data: dict[str, str], indent: str = "  ") -> str:
    lines = [f"{indent}{name}: {{"]
    for k, v in data.items():
        lines.append(f"{indent}  {k}: '{ts_escape(v)}',")
    lines.append(f"{indent}}},")
    return "\n".join(lines)


def replace_or_insert_after(text: str, section: str, new_block: str, after: str) -> str:
    pattern = rf"\n  {section}: \{{"
    m = re.search(pattern, text)
    if m:
        start = m.start() + 1  # keep leading newline handled below
        # find matching closing brace at indent 2
        brace_start = m.end() - 1
        depth = 0
        end = None
        for i, ch in enumerate(text[brace_start:], brace_start):
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    # include trailing comma/newline
                    j = i + 1
                    if j < len(text) and text[j] == ",":
                        j += 1
                    end = j
                    break
        if end is None:
            raise RuntimeError(f"unclosed {section}")
        # m.start() points at newline before section
        return text[: m.start() + 1] + new_block + text[end:]

    # insert after `after` section
    m = re.search(rf"\n  {after}: \{{", text)
    if not m:
        raise RuntimeError(f"cannot find {after} to insert {section}")
    brace_start = m.end() - 1
    depth = 0
    end = None
    for i, ch in enumerate(text[brace_start:], brace_start):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                j = i + 1
                if j < len(text) and text[j] == ",":
                    j += 1
                end = j
                break
    if end is None:
        raise RuntimeError(f"unclosed {after}")
    return text[:end] + "\n" + new_block + text[end:]


